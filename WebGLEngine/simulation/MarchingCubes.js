// Marching Cubes — extracts a triangular surface mesh from a 3D
// scalar field at a chosen isovalue. The classic Lorensen-Cline 1987
// algorithm with the canonical Paul Bourke tables (256 cases).
//
// Reference: http://paulbourke.net/geometry/polygonise/
// Vertex / edge numbering convention (Bourke):
//
//        v4 +--------+ v5
//          /|       /|
//         / |      / |              y
//      v7 +--------+ v6             ^
//        |  |     |  |              |
//        |  v0+---|--+ v1           +---> x
//        | /     | /              /
//        |/      |/              z
//      v3 +-----+ v2
//
// vertices:  0:(0,0,0)  1:(1,0,0)  2:(1,0,1)  3:(0,0,1)
//            4:(0,1,0)  5:(1,1,0)  6:(1,1,1)  7:(0,1,1)
//
// edges:  0:v0→v1   1:v1→v2   2:v2→v3   3:v3→v0
//         4:v4→v5   5:v5→v6   6:v6→v7   7:v7→v4
//         8:v0→v4   9:v1→v5  10:v2→v6  11:v3→v7
//
// Algorithm per cube:
//   1. Build 8-bit case index: bit i set if values[i] < isovalue.
//   2. EDGE_TABLE[case] is a 12-bit mask of which edges are crossed.
//   3. For each crossed edge, linearly interpolate the surface
//      intersection point from the two corner values.
//   4. TRI_TABLE[case] lists edge indices in groups of 3 forming
//      output triangles; terminated by -1.
//
// "Inside" = value < isovalue (matches Bourke's convention; some
// references invert this — the tables here assume this direction).

