// Run: node tools/ship/terrainWasm-selfcheck.mjs
// Gated by tools/ship/selfchecks.mjs (auto-discovered).
//
// GATES the WASM terrain fold-in. The crate itself cannot be exercised here (no Rust toolchain, and the .wasm is
// built on the rig), so this gate pins the property that protects every machine WITHOUT a build:
//
//   WITH NO WASM PRESENT, TERRAIN MUST BE EXACTLY WHAT IT WAS BEFORE THE PATCH.
//
// The golden checksums below were measured by generating the same chunks from the PRE-PATCH world.js and the
// POST-PATCH world.js with the wasm module absent; they matched byte-for-byte. If JS terrain ever changes, these
// trip -- deliberately, so the change is a decision rather than a surprise.
//
// It also runs the real JS-vs-WASM parity harness (tools/terrain-parity.mjs) IF a built crate is present, and
// says plainly that parity is UNVERIFIED when it is not. A check that silently passes when it cannot run is
// decoration.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ENG = path.join(HERE, "..", "..");

let fails = 0;
const ok = (name, cond, detail) => { console.log((cond ? "  PASS  " : "  FAIL  ") + name + (detail ? "   " + detail : "")); if (!cond) fails++; };
const note = (msg) => console.log("  ....  " + msg);

// 1. FALLBACK CONTRACT: with no wasm, every export degrades to null / false rather than throwing
{
    const W = await import("../../world/terrainWasm.js");
    ok("fallback: wasmTerrainReady() is false without a build", W.wasmTerrainReady() === false);
    ok("fallback: wasmGenerateChunk returns null (not a throw)", W.wasmGenerateChunk(0, 0) === null);
    ok("fallback: wasmHeightAt returns null", W.wasmHeightAt(10, 10) === null);
    const okInit = await W.initTerrainWasm({ seed: 1337 });
    ok("fallback: initTerrainWasm resolves false instead of rejecting", okInit === false || okInit === undefined || okInit === null, "returned " + okInit);
}

// 2. THE REGRESSION PIN: JS terrain unchanged when wasm is absent
{
    const { VoxelWorld } = await import("../../world/world.js");
    const w = new VoxelWorld();
    const sum = (v, m) => { let s = 0; for (let i = 0; i < v.length; i++) s = (s + v[i] * (i % m + 1)) >>> 0; return s; };
    const a = w.generateChunk(3, -2); const va = a.voxels || a;
    const b = w.generateChunk(-5, 7); const vb = b.voxels || b;
    ok("JS terrain unchanged: chunk(3,-2) checksum", sum(va, 7) === 54585, "got " + sum(va, 7) + " expected 54585");
    ok("JS terrain unchanged: chunk(-5,7) checksum", sum(vb, 11) === 46482, "got " + sum(vb, 11) + " expected 46482");
    ok("JS terrain unchanged: chunk size", va.length === 16384);
    if (typeof w._heightAt === "function") ok("JS terrain unchanged: _heightAt(40,40)", w._heightAt(40, 40) === 37, "got " + w._heightAt(40, 40));
    ok("wasm generator claimed no tiles (it is absent)", !w._wasmTiles || w._wasmTiles.size === 0);
}

// 3. THE OWNERSHIP RULE: the two generators must never mix inside one tile.
// Parity is bounded, NOT bit-exact (V8 Math.sin vs Rust libm differ by an ulp, and hydraulic erosion amplifies
// that), so a tile generated by one path must never be completed by the other -- that seam would be visible.
{
    const src = fs.readFileSync(path.join(ENG, "world", "world.js"), "utf8");
    ok("ownership: world.js tracks wasm-owned tiles (_wasmTiles)", /_wasmTiles\s*=\s*new Set\(\)/.test(src));
    ok("ownership: a tile the JS erosion cache owns is refused to wasm", /_erosionCache[\s\S]{0,120}JS owns it/.test(src));
    ok("ownership: _heightAt routes queries for wasm tiles into wasm", /_wasmTiles\.has\(/.test(src) && /wasmHeightAt/.test(src));
}

// 4. OPT-OUT SWITCHES exist (a default-on fast path needs a documented off ramp)
{
    const src = fs.readFileSync(path.join(ENG, "world", "world.js"), "utf8");
    ok("opt-out: ?wasmgen=0 / __swekWasmGen / localStorage disable the generator", /wasmgen/.test(src) && /__swekWasmGen/.test(src) && /voxelengine\.terrain\.wasm/.test(src));
    ok("opt-out: ?wasmworker=0 / __swekWasmWorker disable the worker", /wasmworker/.test(src) && /__swekWasmWorker/.test(src));
}

// 5. THE CRATE ships as source with a build script, and the engine does not require it
{
    ok("crate: Rust source present", fs.existsSync(path.join(ENG, "wasm-terrain", "src", "lib.rs")));
    ok("crate: Cargo.toml present", fs.existsSync(path.join(ENG, "wasm-terrain", "Cargo.toml")));
    ok("crate: build script present", fs.existsSync(path.join(ENG, "wasm-terrain", "build_wasm.bat")));
    const bat = fs.readFileSync(path.join(ENG, "wasm-terrain", "build_wasm.bat"), "utf8");
    ok("crate: build script states the engine runs fine WITHOUT the build", /runs fine WITHOUT/i.test(bat));
}

// 6. PARITY: run the real harness if a build exists; otherwise say so instead of passing quietly
{
    const built = fs.existsSync(path.join(ENG, "world", "wasm", "terrain_wasm.js"));
    ok("parity harness is present (tools/terrain-parity.mjs)", fs.existsSync(path.join(ENG, "tools", "terrain-parity.mjs")));
    const psrc = fs.readFileSync(path.join(ENG, "tools", "terrain-parity.mjs"), "utf8");
    ok("parity harness documents its PASS thresholds", /PASS:\s*<2% of voxels differ AND max column-height delta <= 3/.test(psrc));
    ok("parity harness is honest that the paths are NOT byte-interchangeable", /NOT byte-interchangeable/.test(psrc));
    if (!built) {
        note("PARITY NOT VERIFIED HERE: world/wasm/terrain_wasm.js is absent (crate not built).");
        note("This gate therefore proves the JS fallback only. To close the parity claim, on the rig:");
        note("    cd WebGLEngine\\wasm-terrain && build_wasm.bat");
        note("    node tools/terrain-parity.mjs           (and --worley)");
        note("Re-run this selfcheck afterwards and it will execute the harness automatically.");
    } else {
        const r = spawnSync(process.execPath, [path.join(ENG, "tools", "terrain-parity.mjs")], { encoding: "utf8", timeout: 300000 });
        const out = (r.stdout || "") + (r.stderr || "");
        ok("PARITY: JS vs WASM within the documented thresholds", r.status === 0, (out.trim().split("\n").pop() || "").slice(0, 120));
    }
}

console.log("terrainWasm-selfcheck: " + (fails ? fails + " FAILED" : "all pass"));
process.exit(fails ? 1 : 0);
