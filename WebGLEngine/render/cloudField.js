// WHERE THE PUFFS GO. Pure arithmetic: a type name and a seed in, an array of {x,y,z,w,h,colTop,colBot,density}
// out. No GL, no DOM, no Three -- which is what lets two completely different renderers draw the SAME clouds,
// and lets the placement be pinned by an answer key instead of eyeballed.
//
// Keith: "we also have great clouds we made to pass through." They ARE great, and they were also unreachable:
// render/cloudLayer.js is raw WebGL2 with its own shader program and its own inline puff generator, so the
// Three.js planet page could not use them without a second copy of the placement logic. This file is the half
// that ports. cloudLayer.js keeps its WebGL2 drawing and now imports its puffs from here, so the engine's sky
// and the planet's sky are generated by one function rather than by two that started identical.
//
// *** AND THE EXTRACTION FIXED SOMETHING THE ORIGINAL COULD NOT DO: IT IS SEEDED. *** regenerate() called
// Math.random() directly, so the same cloud field could never be rebuilt twice -- which meant no gate could
// assert anything about a specific field, only about ranges. Placement now runs on mulberry32 (the SAME
// deterministic PRNG world/procPlanet.js seeds planets with, integer math only, stable across machines), so a
// seed names a sky. The engine passes a fresh seed per regenerate, so nothing about its behaviour changes.
//
// WHAT PORTS AND WHAT DOES NOT, STATED RATHER THAN ASSUMED: a type's CHARACTER ports -- puff counts, the
// width/height ranges, the tower stacking, the two-tone colours, the density. Its ABSOLUTE ALTITUDE does not:
// TYPES.cumulus sits at y=135 in an engine world whose terrain is tens of units tall, and dropping that number
// onto a planet of radius 17 would put the weather eight radii out in space. So the shell builder takes the
// altitude and a size scale from its CALLER, who is the only one who knows how big the world is.
// ---------------------------------------------------------------------------------------------------------------
"use strict";

import { rng } from "../world/procPlanet.js";   // mulberry32 -- one seeded PRNG for the whole tree

