export const CLOUD_TYPES = Object.keys(TYPES);
/** The type table, read-only to callers. Returns undefined for an unknown name rather than throwing. */
export function cloudType(name) { return TYPES[name]; }

/** One puff's size/colour/density, shared by both placements so a cumulus is a cumulus in either sky. */
function puffLook(t, r, i, n, sizeScale) {
    const rnd = (a, b) => a + r() * (b - a);
    const up = t.tower ? (i / n) : r() * 0.4;       // towering types stack upward; flat types spread sideways
    const w = rnd(t.w[0], t.w[1]) * (t.tower ? (1.0 - up * 0.35) : 1.0);
    const h = rnd(t.h[0], t.h[1]);
    return { up, w: w * sizeScale, h: h * sizeScale, colTop: t.colTop, colBot: t.colBot, density: t.density * rnd(0.8, 1.0) };
}

/**
 * THE FLAT PLACEMENT -- the engine's sky. Clusters scattered across a wrap box centred on (cx,cz) at the type's
 * own altitude. This is render/cloudLayer.js's original regenerate(), moved here verbatim in behaviour and given
 * a seed; the engine calls it with a fresh seed each time, so its sky is as varied as it was before.
 */
export function buildPuffsFlat({ type, cx = 0, cz = 0, region = 480, seed = 1 } = {}) {
    const t = TYPES[type];
    if (!t) return [];
    const r = rng(seed >>> 0);
    const rnd = (a, b) => a + r() * (b - a);
    const puffs = [];
    for (let c = 0; c < t.clouds; c++) {
        const baseX = cx + rnd(-region, region), baseZ = cz + rnd(-region, region), baseY = t.altitude;
        const n = Math.round(rnd(t.puffs[0], t.puffs[1]));
        for (let i = 0; i < n; i++) {
            const L = puffLook(t, r, i, n, 1);
            puffs.push({
                x: baseX + rnd(-t.spreadXZ, t.spreadXZ) * (t.tower ? 0.5 : 1.0),
                y: baseY + L.up * t.spreadY + rnd(-4, 4),
                z: baseZ + rnd(-t.spreadXZ, t.spreadXZ) * (t.tower ? 0.5 : 1.0),
                w: L.w, h: L.h, colTop: L.colTop, colBot: L.colBot, density: L.density,
            });
        }
    }
    return puffs;
}

/** Unit direction from spherical offsets around `dir`, using a geographic tangent frame (east/north). */
function offsetDir(dir, dEast, dNorth) {
    const d = norm(dir);
    let e = [d[2], 0, -d[0]];
    const l = Math.hypot(e[0], e[1], e[2]);
    e = l < 1e-6 ? [1, 0, 0] : [e[0] / l, e[1] / l, e[2] / l];
    const n = norm([d[1] * e[2] - d[2] * e[1], d[2] * e[0] - d[0] * e[2], d[0] * e[1] - d[1] * e[0]]);
    return norm([d[0] + e[0] * dEast + n[0] * dNorth, d[1] + e[1] * dEast + n[1] * dNorth, d[2] + e[2] * dEast + n[2] * dNorth]);
}
function norm(a) { const l = Math.hypot(a[0], a[1], a[2]) || 1; return [a[0] / l, a[1] / l, a[2] / l]; }

/**
 * *** THE SPHERICAL PLACEMENT -- weather on a WORLD, which is the half that did not exist. *** Clusters are
 * scattered inside a cone of half-angle `coverage` around `dir` (the part of the planet you are arriving at:
 * generating a whole globe's weather to fly through one patch of it is puffs nobody sees), and each sits on a
 * shell at `groundRadius + altitude`. "Up" for a puff is the planet's own radial direction there, so a towering
 * cumulonimbus grows away from the surface rather than along some world axis.
 *
 * ALTITUDE AND sizeScale COME FROM THE CALLER, deliberately -- see the header. A type's proportions are its
 * character and travel; its absolute altitude is a fact about the world it was written for and does not.
 */
export function buildPuffsShell({ type, center = [0, 0, 0], groundRadius = 17, altitude = 1.2,
                                  dir = [0, 0, 1], coverage = 0.45, sizeScale = 0.02, seed = 1 } = {}) {
    const t = TYPES[type];
    if (!t) return [];
    const r = rng(seed >>> 0);
    const rnd = (a, b) => a + r() * (b - a);
    const shell = groundRadius + altitude;
    const puffs = [];
    for (let c = 0; c < t.clouds; c++) {
        // a cluster centre inside the cone. sqrt keeps the scatter AREA-uniform rather than bunching at the
        // middle, which a naive uniform radius would do.
        const a = r() * Math.PI * 2, rad = Math.sqrt(r()) * coverage;
        const base = offsetDir(dir, Math.cos(a) * rad, Math.sin(a) * rad);
        const n = Math.round(rnd(t.puffs[0], t.puffs[1]));
        for (let i = 0; i < n; i++) {
            const L = puffLook(t, r, i, n, sizeScale);
            // spread within the cluster, expressed as an ANGLE so it is a real distance on the shell
            const sx = (rnd(-t.spreadXZ, t.spreadXZ) * (t.tower ? 0.5 : 1.0)) * sizeScale / shell;
            const sz = (rnd(-t.spreadXZ, t.spreadXZ) * (t.tower ? 0.5 : 1.0)) * sizeScale / shell;
            const d = offsetDir(base, sx, sz);
            const rr = shell + (L.up * t.spreadY + rnd(-4, 4)) * sizeScale;   // radial: the tower's own height
            puffs.push({
                x: center[0] + d[0] * rr, y: center[1] + d[1] * rr, z: center[2] + d[2] * rr,
                w: L.w, h: L.h, colTop: L.colTop, colBot: L.colBot, density: L.density,
                radius: rr,                        // handed out so a caller can test the shell without re-deriving it
                up: d,                             // the planet's radial direction here -- a puff's own "up"
            });
        }
    }
    return puffs;
}
